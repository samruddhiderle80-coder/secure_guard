import React, { useEffect, useState } from 'react';
import { useLocation, Link, useParams } from 'react-router-dom';
import { ShieldCheck, ShieldAlert, AlertTriangle, ArrowRight, LayoutDashboard, CheckCircle2, XCircle } from 'lucide-react';
import { ScoreRing } from '../../components/common/ScoreRing';
import { RiskBadge } from '../../components/common/RiskBadge';
import { fetchApi } from '../../lib/api';
import { LoadingSpinner } from '../../components/common/LoadingSpinner';

export const AssessmentResults: React.FC = () => {
  const location = useLocation();
  const { id } = useParams();

  const [result, setResult] = useState<any>(location.state?.result || null);
  const [loading, setLoading] = useState(!location.state?.result);

  useEffect(() => {
    if (!result) {
      const targetId = id || 'latest';
      fetchApi<any>(`/api/assessment/results/${targetId}`)
        .then(res => {
          setResult(res);
        })
        .catch(err => {
          console.error('Failed to load assessment from database:', err);
        })
        .finally(() => setLoading(false));
    }
  }, [id, result]);

  if (loading) {
    return <LoadingSpinner label="Loading assessment records from database..." />;
  }

  if (!result) {
    return (
      <div className="text-center py-12 space-y-4">
        <h2 className="text-xl font-bold text-slate-800">No Assessment Results Found</h2>
        <p className="text-xs text-slate-500">Take an assessment to record your security score in the database.</p>
        <Link to="/assessment" className="inline-block px-4 py-2 bg-brand-600 text-white font-bold rounded-xl text-xs">
          Take Security Assessment
        </Link>
      </div>
    );
  }

  const score = result.score || result.total_score || 0;
  const riskLevel = result.riskLevel || result.risk_level || 'MODERATE';
  const categoryScores = result.categoryScores || result.category_scores || {
    password: 0, mfa: 0, privacy: 0, phishing: 0, applications: 0, recovery: 0, awareness: 0
  };
  const findings = result.findings || [];

  return (
    <div className="max-w-4xl mx-auto space-y-8">
      {/* Header Banner */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-card flex flex-col md:flex-row items-center justify-between gap-6">
        <div>
          <span className="text-xs font-bold uppercase tracking-widest text-brand-600 bg-brand-50 px-3 py-1 rounded-full border border-brand-200">
            Assessment Complete
          </span>
          <h1 className="text-2xl font-extrabold text-slate-900 mt-2">
            Your Security Evaluation Results
          </h1>
          <p className="text-xs text-slate-500 mt-1">
            Generated by Social Guard Risk Scoring Engine and persisted into the database.
          </p>
        </div>

        <div className="flex items-center gap-3">
          <Link
            to="/dashboard"
            className="inline-flex items-center gap-1.5 px-4 py-2.5 rounded-xl text-xs font-bold text-slate-700 bg-slate-100 hover:bg-slate-200 transition-colors"
          >
            <LayoutDashboard size={16} /> Dashboard
          </Link>
        </div>
      </div>

      {/* Main Score & Risk Summary */}
      <div className="grid grid-cols-1 md:grid-cols-12 gap-6 items-center">
        <div className="md:col-span-5 bg-white p-6 rounded-2xl border border-slate-200 shadow-card flex flex-col items-center justify-center">
          <ScoreRing score={score} size={180} strokeWidth={14} label="Final Security Score" />
          <div className="mt-4">
            <RiskBadge level={riskLevel} size="lg" />
          </div>
        </div>

        <div className="md:col-span-7 bg-white p-6 rounded-2xl border border-slate-200 shadow-card space-y-4">
          <h3 className="text-base font-bold text-slate-900 border-b border-slate-100 pb-2">
            Executive Summary
          </h3>
          <p className="text-xs text-slate-600 leading-relaxed">
            {result.summaryText || (
              score >= 80
                ? 'Your security practices demonstrate robust account controls across password management, 2FA implementation, and privacy safeguards.'
                : 'Several high-priority risks were detected in your configuration. Review the findings below and complete recommended checklists.'
            )}
          </p>

          <div className="pt-2 grid grid-cols-2 gap-3 text-xs">
            <div className="p-3 bg-emerald-50 rounded-xl border border-emerald-200/80">
              <span className="font-bold text-emerald-800 block mb-1 flex items-center gap-1">
                <CheckCircle2 size={14} /> Key Strengths
              </span>
              <ul className="text-emerald-700 space-y-1">
                {categoryScores.mfa >= 70 && <li>✓ MFA protection active</li>}
                {categoryScores.password >= 70 && <li>✓ Strong password habits</li>}
                {categoryScores.phishing >= 70 && <li>✓ Phishing awareness verified</li>}
                {categoryScores.mfa < 70 && categoryScores.password < 70 && <li>Baseline assessment recorded</li>}
              </ul>
            </div>

            <div className="p-3 bg-rose-50 rounded-xl border border-rose-200/80">
              <span className="font-bold text-rose-800 block mb-1 flex items-center gap-1">
                <AlertTriangle size={14} /> Priority Attention
              </span>
              <ul className="text-rose-700 space-y-1">
                {findings.length > 0 ? (
                  findings.slice(0, 2).map((f: any, i: number) => (
                    <li key={i} className="truncate">• {f.title}</li>
                  ))
                ) : (
                  <li>• No severe vulnerabilities found</li>
                )}
              </ul>
            </div>
          </div>
        </div>
      </div>

      {/* Category Breakdown Bars */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-card space-y-4">
        <h3 className="text-base font-bold text-slate-900 border-b border-slate-100 pb-2">
          Domain Breakdown Analysis
        </h3>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {Object.entries(categoryScores).map(([cat, sc]: [string, any]) => (
            <div key={cat} className="p-3 bg-slate-50 rounded-xl border border-slate-200 space-y-1.5">
              <div className="flex justify-between items-center text-xs font-bold">
                <span className="uppercase text-slate-700 tracking-wider">{cat}</span>
                <span className={sc >= 75 ? 'text-emerald-600' : sc >= 50 ? 'text-amber-600' : 'text-rose-600'}>
                  {sc}%
                </span>
              </div>
              <div className="w-full bg-slate-200 h-2 rounded-full overflow-hidden">
                <div
                  className={`h-full transition-all duration-500 ${
                    sc >= 75 ? 'bg-emerald-500' : sc >= 50 ? 'bg-amber-500' : 'bg-rose-500'
                  }`}
                  style={{ width: `${sc}%` }}
                />
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Findings & Remediation Section */}
      <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-card space-y-4">
        <h3 className="text-base font-bold text-slate-900 border-b border-slate-100 pb-2 flex items-center justify-between">
          <span>Identified Security Findings ({findings.length})</span>
          <span className="text-xs text-slate-400 font-normal">Ranked by risk severity</span>
        </h3>

        {findings.length === 0 ? (
          <div className="p-4 bg-emerald-50 border border-emerald-200 rounded-xl text-center text-xs text-emerald-800 font-medium">
            No critical security vulnerabilities identified in your submitted assessment responses.
          </div>
        ) : (
          <div className="space-y-3">
            {findings.map((finding: any, idx: number) => (
              <div
                key={idx}
                className="p-4 rounded-xl border border-slate-200 bg-slate-50 space-y-2 text-xs transition-colors hover:bg-slate-100/70"
              >
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2">
                    <span
                      className={`px-2 py-0.5 rounded font-black text-[10px] uppercase ${
                        finding.severity === 'HIGH'
                          ? 'bg-rose-100 text-rose-800'
                          : finding.severity === 'MEDIUM'
                          ? 'bg-amber-100 text-amber-800'
                          : 'bg-emerald-100 text-emerald-800'
                      }`}
                    >
                      {finding.severity}
                    </span>
                    <h4 className="font-bold text-slate-900">{finding.title}</h4>
                  </div>
                </div>

                <p className="text-slate-600 leading-relaxed">{finding.description}</p>

                <div className="pt-2 border-t border-slate-200/80 flex items-start gap-2 text-slate-700 bg-white p-2.5 rounded-lg border border-slate-200">
                  <span className="font-bold text-brand-700 shrink-0">Remediation:</span>
                  <span className="font-medium text-slate-600">{finding.recommendation}</span>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
};
